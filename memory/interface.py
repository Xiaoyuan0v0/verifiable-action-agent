"""Lab 2 扩展位置。实验一不注册记忆工具，不用聊天历史假冒长期记忆。"""
from typing import Protocol

class MemoryStore(Protocol):
    def propose(self, *, content: str, user_scope: str, source: str) -> dict: ...
    def retrieve(self, *, query: str, user_scope: str, version: str) -> list[dict]: ...
    def supersede(self, *, memory_id: str, replacement: dict, user_scope: str) -> None: ...
    def delete(self, *, memory_id: str, user_scope: str) -> None: ...
